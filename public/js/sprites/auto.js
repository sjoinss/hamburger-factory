// M7 도트: 센서, 제어 회로, 주문 묶음, 주문 인식기(2x2), 합류 포장기
import { blank, plot, rect, frame } from './draw.js';

// 센서: 철제 받침 위 둥근 렌즈
export const SENSOR = (() => {
  let r = blank(16, 16);
  r = rect(r, 3, 9, 10, 4, '1');
  r = frame(r, 3, 9, 10, 4, 'k');
  r = rect(r, 5, 4, 6, 6, '2');
  r = frame(r, 5, 4, 6, 6, 'k');
  r = rect(r, 6, 5, 4, 4, 'p');
  r = plot(r, [[6, 5, '3'], [7, 5, 'l'], [9, 8, 'P'], [8, 8, 'P']]);
  r = plot(r, [[4, 10, 'y'], [11, 10, 'G']]);
  return rect(r, 4, 13, 10, 1, 'K');
})();

// 제어 회로: 녹색 기판, 금속 배선, 칩
export const CIRCUIT = (() => {
  let r = blank(16, 16);
  r = rect(r, 2, 3, 12, 10, 'G');
  r = frame(r, 2, 3, 12, 10, 'k');
  r = rect(r, 6, 6, 4, 4, 'K');
  r = plot(r, [[6, 6, '1'], [9, 9, '1']]);
  for (const x of [3, 4, 11, 12]) r = plot(r, [[x, 5, '3'], [x, 10, '3']]);
  r = plot(r, [[5, 7, '3'], [5, 8, '3'], [10, 7, '3'], [10, 8, '3'], [7, 4, 'y'], [8, 11, 'y']]);
  return rect(r, 3, 13, 12, 1, 'K');
})();

// 주문 묶음: 종이봉투 + 번호표
export const ORDER_BAG = (() => {
  let r = blank(16, 16);
  r = rect(r, 3, 4, 10, 10, 'f');
  r = rect(r, 3, 4, 10, 1, 'F');
  r = frame(r, 3, 4, 10, 10, 'k');
  r = plot(r, [[6, 2, 'k'], [6, 3, 'k'], [9, 2, 'k'], [9, 3, 'k'], [7, 1, 'k'], [8, 1, 'k']]); // 손잡이
  r = rect(r, 5, 7, 6, 4, 'l'); // 번호표
  r = frame(r, 5, 7, 6, 4, 'r');
  r = plot(r, [[7, 8, 'K'], [8, 8, 'K'], [7, 9, 'K']]);
  return rect(r, 4, 14, 10, 1, 'K');
})();

const frames3 = (make) => [0, 1, 2].map(make);

// 주문 인식기 (2x2): 주문표가 나오는 단말기. 화면에 주문서 줄이 흐르고 안테나 불이 깜박인다.
export const ORDER_READER = frames3((f) => {
  let r = blank(32, 32);
  r = rect(r, 1, 8, 30, 22, '1');
  r = rect(r, 2, 9, 28, 1, '2');
  r = frame(r, 1, 8, 30, 22, 'k');
  r = rect(r, 2, 30, 30, 2, 'K');
  // 화면
  r = rect(r, 4, 11, 16, 11, 'K');
  r = frame(r, 3, 10, 18, 13, 'k');
  for (let i = 0; i < 4; i++) {
    const y = 12 + ((i * 3 + f) % 10);
    r = rect(r, 5, y, 6 + ((i * 5) % 8), 1, f === 0 && i === 0 ? 'y' : 'G');
  }
  // 영수증 출력구
  r = rect(r, 23, 11, 6, 2, 'K');
  r = rect(r, 24, 4 + f, 4, 8 - f, 'l');
  r = frame(r, 24, 4 + f, 4, 8 - f, 'k');
  r = plot(r, [[25, 6 + f, 'n'], [26, 8, 'n']]);
  // 버튼과 안테나
  r = plot(r, [[23, 16, 'y'], [25, 16, 'G'], [27, 16, 'R'], [23, 19, '3'], [25, 19, '3'], [27, 19, '3']]);
  r = rect(r, 6, 2, 1, 6, '2');
  r = plot(r, [[6, 1, f === 1 ? 'y' : 'r'], [5, 1, 'k'], [7, 1, 'k']]);
  // 받침 줄무늬
  for (let x = 3; x < 29; x += 4) r = plot(r, [[x, 26, 'y'], [x + 1, 26, 'K']]);
  return r;
});

// 합류 포장기: 테이프 붙이는 상자 + 위로 나오는 봉투, 앞쪽 화살표 (회전하면 같이 돈다)
export const BUNDLER = frames3((f) => {
  let r = blank(16, 16);
  r = rect(r, 0, 4, 16, 11, '1');
  r = rect(r, 1, 5, 14, 1, '2');
  r = frame(r, 0, 4, 16, 11, 'k');
  r = rect(r, 1, 15, 15, 1, 'K');
  r = rect(r, 3, 7, 8, 6, 'f');
  r = frame(r, 3, 7, 8, 6, 'k');
  r = rect(r, 3, 9, 8, 1, f ? 'y' : 'F'); // 테이프
  r = plot(r, [[6, 8 - (f % 2), 'r'], [7, 8 - (f % 2), 'r']]);
  // 오른쪽(앞) 화살표
  r = plot(r, [[12, 8, 'y'], [13, 9, 'y'], [12, 10, 'y'], [14, 9, 'y']]);
  return r;
});
