// 저장/출고 기계 도트 (M5): 깔때기 호퍼 2x2, 사일로 2x3, 출고 게이트 1x2
import { blank, plot, rect, frame } from './draw.js';

// 깔때기 호퍼: 위가 넓은 깔때기, 아래 주둥이. 리벳 위치는 일부러 어긋나게.
export const HOPPER = (() => {
  let r = blank(32, 32);
  // 위 테두리 (넓은 입구)
  r = rect(r, 0, 1, 32, 4, '2');
  r = rect(r, 1, 2, 30, 1, '3');
  r = frame(r, 0, 1, 32, 4, 'k');
  // 깔때기 몸통: 한 줄 내려갈 때마다 양쪽이 1px 씩 좁아진다
  for (let y = 5; y < 24; y++) {
    const inset = Math.floor((y - 5) * 0.55);
    r = rect(r, 1 + inset, y, 30 - inset * 2, 1, '1');
    r = plot(r, [[inset, y, 'k'], [31 - inset, y, 'k'], [2 + inset, y, '2']]);
  }
  // 입구 안쪽 어두운 구멍
  r = rect(r, 4, 5, 24, 3, 'K');
  // 주둥이 + 받침
  r = rect(r, 12, 24, 8, 4, '2');
  r = frame(r, 12, 24, 8, 4, 'k');
  r = rect(r, 6, 28, 20, 3, '1');
  r = frame(r, 6, 28, 20, 3, 'k');
  r = rect(r, 7, 31, 20, 1, 'K');
  // 경고 띠, 리벳, 녹
  for (let x = 13; x < 19; x++) r = plot(r, [[x, 26, x % 2 ? 'y' : 'K']]);
  r = plot(r, [[3, 3, 'k'], [27, 2, 'k'], [9, 12, '3'], [22, 15, '3'], [10, 18, 'r'], [11, 19, 'r'], [21, 9, 'd']]);
  return r;
})();

// 사일로: 키 큰 원통, 띠 세 줄, 옆 사다리
export const SILO = (() => {
  let r = blank(32, 48);
  r = rect(r, 2, 4, 28, 40, '2');
  r = rect(r, 3, 4, 3, 40, '3'); // 빛 받는 면
  r = rect(r, 25, 4, 4, 40, '1'); // 그늘
  r = frame(r, 2, 4, 28, 40, 'k');
  // 둥근 지붕
  r = rect(r, 6, 0, 20, 4, '2');
  r = rect(r, 4, 2, 24, 2, '2');
  r = plot(r, [[6, 0, 'k'], [25, 0, 'k'], [4, 2, 'k'], [27, 2, 'k'], [5, 1, 'k'], [26, 1, 'k']]);
  r = rect(r, 7, 0, 18, 1, 'k');
  for (const y of [12, 24, 36]) r = rect(r, 2, y, 28, 1, 'k');
  // 사다리 (오른쪽)
  for (let y = 6; y < 42; y += 3) r = plot(r, [[27, y, 'K'], [28, y, 'K']]);
  r = rect(r, 26, 5, 1, 38, 'K');
  // 바닥 그림자, 녹 얼룩
  r = rect(r, 3, 44, 28, 1, 'K');
  r = rect(r, 4, 45, 26, 1, 'K');
  r = plot(r, [[9, 30, 'r'], [9, 31, 'r'], [10, 32, 'd'], [18, 15, 'd']]);
  return r;
})();

// 출고 게이트: 세로 1x2 (기본 방향 = 오른쪽으로 내보냄). 오른쪽 위 칸에 셔터.
export const GATE = (() => {
  let r = blank(16, 32);
  r = rect(r, 0, 0, 16, 31, '1');
  r = frame(r, 0, 0, 16, 31, 'k');
  r = rect(r, 1, 1, 14, 1, '2');
  // 셔터 (내보내는 쪽)
  r = rect(r, 9, 3, 6, 11, '3');
  for (let y = 4; y < 14; y += 2) r = rect(r, 9, y, 6, 1, '2');
  r = frame(r, 9, 3, 6, 11, 'k');
  // 화살표
  r = plot(r, [[3, 8, 'y'], [4, 8, 'y'], [5, 8, 'y'], [6, 8, 'y'], [5, 7, 'y'], [5, 9, 'y'], [6, 7, 'k'], [6, 9, 'k'], [7, 8, 'k']]);
  // 아래 칸: 경고 빗금 판
  for (let y = 18; y < 28; y++) for (let x = 2; x < 14; x++) r = plot(r, [[x, y, (x + y) % 4 < 2 ? 'y' : 'K']]);
  r = frame(r, 2, 18, 12, 10, 'k');
  r = rect(r, 1, 31, 15, 1, 'K');
  r = plot(r, [[3, 15, '3'], [12, 29, 'd']]);
  return r;
})();
